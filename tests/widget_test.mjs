// <jade-chat-widget>: the floating button, the panel, lazy loading of the chat, Esc, the reply dot.
import { start, sleep } from './_harness.mjs';
const t = await start();
const { ok, ev, page } = t;
await ev(() => { document.getElementById('app').innerHTML = '<jade-chat-widget id="w" title="Acme support" subtitle="We reply in minutes" greeting="Hi! How can we help?" suggestions=\'["Where is my order?"]\'></jade-chat-widget>'; });
await page.waitForFunction(() => customElements.get('jade-chat-widget'));
const W = page.locator('#w');
const fab = W.getByRole('button', { name: 'Open chat: Acme support' });
await fab.waitFor();
ok(!t.loaded().includes('chat.js'), 'the chat is not loaded before the first open');
await ev(() => { const w = document.getElementById('w'); w.handler = async (text, r) => { r.append('You said: ' + text); }; window.EV = []; w.addEventListener('jade-open', () => EV.push('open')); w.addEventListener('jade-close', () => EV.push('close')); });
await fab.click();
const dlg = W.getByRole('dialog', { name: 'Acme support' });
await dlg.waitFor();
await W.getByText('Hi! How can we help?').waitFor();
ok(t.loaded().includes('chat.js'), 'opening loads the chat');
ok(await W.getByText('We reply in minutes').isVisible(), 'the subtitle shows');
ok((await W.locator('.fab').getAttribute('aria-expanded')) === 'true', 'the button says it is expanded');
await W.getByRole('button', { name: 'Where is my order?' }).click();
await W.getByText('You said: Where is my order?').waitFor();
ok(true, 'the handler set before loading answers');
await W.locator('textarea').first().focus();
await page.keyboard.press('Escape');
await sleep(100);
ok(!(await dlg.isVisible()) && (await ev(() => document.getElementById('w').hasAttribute('open'))) === false, 'Esc closes');
ok((await ev(() => document.getElementById('w').shadowRoot.activeElement?.className)) === 'fab', 'focus goes back to the button');
await ev(() => document.getElementById('w').chat().then(c => c.send('ping')));
await sleep(300);
ok(await W.locator('.dot').isVisible(), 'a reply while closed shows a dot');
await ev(() => document.getElementById('w').setAttribute('open', ''));
await dlg.waitFor(); ok(!(await W.locator('.dot').isVisible()), 'opening (by attribute) clears the dot');
await W.getByRole('button', { name: 'Close chat' }).first().click(); await sleep(100);
ok((await ev(() => EV.join())) === 'open,close,open,close', 'jade-open and jade-close: ' + (await ev(() => EV.join())));
await ev(() => document.getElementById('w').setAttribute('position', 'bottom-left'));
const box = await W.locator('.fab').boundingBox(); ok(box.x < 100, 'bottom-left moves it left');
await page.setViewportSize({ width: 390, height: 700 }); await ev(() => document.getElementById('w').open()); await sleep(250);
const pb = await W.locator('.panel').boundingBox(); ok(pb.width === 390 && pb.height === 700, 'on a phone the panel fills the screen');
if (process.env.JUI_SHOTS) { await page.setViewportSize({ width: 900, height: 700 }); await ev(() => document.getElementById('w').setAttribute('position', 'bottom-right')); await page.screenshot({ path: '/tmp/widget.png' }); }
await t.done();
